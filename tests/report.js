#!/usr/bin/env node
'use strict';
/**
 * Regenerate docs/RESULTS.md: accuracy of the offline engine on every gold set (tests/gold/), plus latency and size figures.
 *   node --expose-gc tests/report.js
 */
const fs = require('fs');
const path = require('path');
const { Engine } = require('../engine/src/engine');
const ROOT = path.join(__dirname, '..');
const strip = s => s.replace(/‌/g, '');

const lexTsv = fs.readFileSync(path.join(ROOT, 'data/build/lexicon.tsv'), 'utf8');
const tLoad = Date.now();
const eng = Engine.fromTSV(lexTsv);
const loadMs = Date.now() - tLoad;
const aliasTsv = fs.readFileSync(path.join(ROOT, 'data/aliases.tsv'), 'utf8');
const bg = path.join(ROOT, 'data/build/bigrams.tsv');
if (fs.existsSync(bg)) eng.setBigrams(fs.readFileSync(bg, 'utf8'));
if (global.gc) global.gc();
const heapMb = Math.round(process.memoryUsage().heapUsed / 1048576);

function loadGold(p) {
  const rows = [], seen = new Set();
  for (const line of fs.readFileSync(p, 'utf8').split('\n')) {
    if (!line.trim() || line[0] === '#') continue;
    const [fin, fa] = line.split('\t');
    if (!fa || /\s/.test(fin.trim())) continue;
    const k = fin + '\t' + fa; if (seen.has(k)) continue; seen.add(k);
    rows.push({ fin: fin.trim(), gold: fa.split('|').map(s => strip(s.trim())) });
  }
  return rows;
}
const rank = (list, gold) => { for (let i = 0; i < list.length; i++) if (gold.includes(list[i])) return i + 1; return 0; };
function metrics(rs) {
  const n = rs.length, at = k => rs.filter(r => r > 0 && r <= k).length / n;
  return { n, top1: at(1), top3: at(3), top5: at(5), mrr: rs.reduce((s, r) => s + (r ? 1 / r : 0), 0) / n };
}
const pct = x => (100 * x).toFixed(1) + '%';
const lat = [];

const SETS = [
  { name: 'natural_1 (tuned on 80%)', gold: 'tests/gold/natural_1.tsv', aliases: true },
  { name: 'natural_2 held-out (never tuned on)', gold: 'tests/gold/natural_2_heldout.tsv', aliases: false },
  { name: 'inflected_3 (clitics / plurals)', gold: 'tests/gold/inflected_3.tsv', aliases: false },
];
let md = ['# Results', '', `Generated by \`node tests/report.js\` on ${new Date().toISOString().slice(0, 10)}. Offline engine = ${eng.lex.words.length.toLocaleString()} words.`,
  'The gold sets are hand-written (`tests/gold/`); `natural_2_heldout` was written after the parameters were frozen and is never used for tuning.', '',
  '| benchmark | n | top-1 | top-3 | top-5 | MRR |', '|---|---:|---:|---:|---:|---:|'];
for (const S of SETS) {
  eng.setAliases(S.aliases ? aliasTsv : new Map());
  const rows = loadGold(path.join(ROOT, S.gold));
  const ours = [];
  for (const r of rows) {
    const t = process.hrtime.bigint();
    const c = eng.candidates(r.fin, { max: 9 }).map(x => strip(x.text));
    lat.push(Number(process.hrtime.bigint() - t) / 1e6);
    ours.push(rank(c, r.gold));
  }
  const mo = metrics(ours);
  md.push(`| ${S.name} | ${mo.n} | ${pct(mo.top1)} | ${pct(mo.top3)} | ${pct(mo.top5)} | ${mo.mrr.toFixed(3)} |`);
}
// context on sentences
eng.setAliases(new Map());
let ctx = null;
try {
  const st = { n: 0, a: 0, b: 0 };
  for (const line of fs.readFileSync(path.join(ROOT, 'tests/gold/sentences_4.tsv'), 'utf8').split('\n')) {
    if (!line.trim() || line[0] === '#') continue;
    const [fin, fa] = line.split('\t'); const fw = fin.split(/\s+/), pw = fa.split(/\s+/);
    for (let i = 0; i < fw.length; i++) {
      const r0 = rank(eng.candidates(fw[i], { max: 9 }).map(x => strip(x.text)), [strip(pw[i])]);
      const r1 = rank(eng.candidates(fw[i], { max: 9, prev: i ? pw[i - 1] : null }).map(x => strip(x.text)), [strip(pw[i])]);
      st.n++; st.a += r0 === 1; st.b += r1 === 1;
    }
  }
  ctx = st;
} catch (e) { /* optional */ }
lat.sort((a, b) => a - b);
const q = p => lat[Math.min(lat.length - 1, Math.floor(p * lat.length))];
md.push('', '## Previous-word context', '',
  ctx ? `On ${ctx.n} tokens of chat sentences (\`tests/gold/sentences_4.tsv\`): top-1 ${pct(ctx.a / ctx.n)} without context → ${pct(ctx.b / ctx.n)} with the previous word.` : '_(bigram file not built)_',
  '', '## Speed', '', `Per query in Node ${process.version} on this machine over ${lat.length} gold inputs: median ${q(0.5).toFixed(1)} ms, p95 ${q(0.95).toFixed(1)} ms, max ${lat[lat.length - 1].toFixed(1)} ms.`,
  '', `Cold start: engine ready in ${loadMs} ms (parse + index + character-LM training); JS heap with lexicon, bigrams and engine loaded ≈ ${heapMb} MB (run with \`node --expose-gc\` for a clean figure).`, '');
fs.writeFileSync(path.join(ROOT, 'docs/RESULTS.md'), md.join('\n'));
console.log(md.join('\n'));
